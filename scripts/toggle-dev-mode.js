#!/usr/bin/env node

/**
 * GameGen Dev Mode Toggle Script
 * 
 * This script helps you easily toggle dev mode on/off by managing environment variables
 * 
 * Usage:
 *   node scripts/toggle-dev-mode.js on   # Enable dev mode (auto-login)
 *   node scripts/toggle-dev-mode.js off  # Disable dev mode (require authentication)
 *   node scripts/toggle-dev-mode.js      # Show current status
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ENV_FILE = path.join(__dirname, '..', '.env.local');

function readEnvFile() {
  if (!fs.existsSync(ENV_FILE)) {
    return {};
  }
  
  const content = fs.readFileSync(ENV_FILE, 'utf8');
  const env = {};
  
  content.split('\n').forEach(line => {
    line = line.trim();
    if (line && !line.startsWith('#')) {
      const [key, ...valueParts] = line.split('=');
      if (key && valueParts.length > 0) {
        env[key.trim()] = valueParts.join('=').trim();
      }
    }
  });
  
  return env;
}

function writeEnvFile(env) {
  const lines = [
    '# Development Mode Configuration',
    '# Generated by toggle-dev-mode.js script',
    '',
    '# Node environment',
    `NODE_ENV=${env.NODE_ENV || 'development'}`,
    '',
    '# Dev Mode Settings - Set to false to disable auto-login',
    `DEV_MODE_ENABLED=${env.DEV_MODE_ENABLED || 'false'}`,
    `NEXT_PUBLIC_DEV_MODE_ENABLED=${env.NEXT_PUBLIC_DEV_MODE_ENABLED || 'false'}`,
    '',
    '# Supabase configuration - LOCAL DEVELOPMENT',
    `NEXT_PUBLIC_SUPABASE_URL=${env.NEXT_PUBLIC_SUPABASE_URL || 'http://127.0.0.1:54321'}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${env.NEXT_PUBLIC_SUPABASE_ANON_KEY || 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZS1kZW1vIiwicm9sZSI6ImFub24iLCJleHAiOjE5ODM4MTI5OTZ9.CRXP1A7WOeoJeXxjNni43kdQwgnWNReilDMblYTn_I0'}`,
    '',
    '# Add your Stripe configuration here:',
    `# STRIPE_SECRET_KEY=${env.STRIPE_SECRET_KEY || 'your_stripe_secret_key'}`,
    `# NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY=${env.NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY || 'your_stripe_publishable_key'}`,
    '',
    '# Other environment variables...',
    ''
  ];
  
  // Add any existing env vars that aren't handled above
  Object.keys(env).forEach(key => {
    if (!key.startsWith('NODE_ENV') && 
        !key.startsWith('DEV_MODE') && 
        !key.startsWith('NEXT_PUBLIC_DEV_MODE') &&
        !key.startsWith('NEXT_PUBLIC_SUPABASE') &&
        !key.startsWith('STRIPE')) {
      lines.push(`${key}=${env[key]}`);
    }
  });
  
  fs.writeFileSync(ENV_FILE, lines.join('\n'));
}

function showStatus() {
  const env = readEnvFile();
  const devModeEnabled = env.DEV_MODE_ENABLED === 'true';
  const publicDevModeEnabled = env.NEXT_PUBLIC_DEV_MODE_ENABLED === 'true';
  const nodeEnv = env.NODE_ENV || 'not set';
  
  console.log('\n🎮 GameGen Dev Mode Status:');
  console.log(`   NODE_ENV: ${nodeEnv}`);
  console.log(`   DEV_MODE_ENABLED: ${env.DEV_MODE_ENABLED || 'false'}`);
  console.log(`   NEXT_PUBLIC_DEV_MODE_ENABLED: ${env.NEXT_PUBLIC_DEV_MODE_ENABLED || 'false'}`);
  
  if (devModeEnabled && publicDevModeEnabled && nodeEnv === 'development') {
    console.log('\n✅ Dev Mode: ENABLED (auto-login active)');
    console.log('   - You will be automatically logged in as developer@gamegen.com');
    console.log('   - Dashboard and protected routes are accessible without authentication');
    console.log('   - Orange dev mode banner will be visible');
    console.log('   - Game Creator, Profile, and Settings are accessible');
    console.log('   - All GameGen platform features available for testing');
  } else {
    console.log('\n❌ Dev Mode: DISABLED (normal authentication required)');
    console.log('   - You need to sign up/login normally');
    console.log('   - Protected routes will redirect to login page');
    console.log('   - Full Supabase authentication required');
  }
  
  console.log('\nUsage:');
  console.log('   node scripts/toggle-dev-mode.js on   # Enable dev mode');
  console.log('   node scripts/toggle-dev-mode.js off  # Disable dev mode');
  console.log('   make dev-mode-on                     # Enable via Makefile');
  console.log('   make dev-mode-off                    # Disable via Makefile');
  console.log('\nGameGen Protected Routes in Dev Mode:');
  console.log('   - /dashboard - Main user dashboard');
  console.log('   - /game-creator - Pixel art game creation tool');
  console.log('   - /profile - User profile management');
  console.log('   - /settings - Account settings');
  console.log('   - /analytics - Game analytics (if available)');
  console.log('\n');
}

function enableDevMode() {
  const env = readEnvFile();
  env.NODE_ENV = 'development';
  env.DEV_MODE_ENABLED = 'true';
  env.NEXT_PUBLIC_DEV_MODE_ENABLED = 'true';
  
  writeEnvFile(env);
  
  console.log('✅ GameGen Dev Mode ENABLED');
  console.log('   - Auto-login is now active');
  console.log('   - Mock user: developer@gamegen.com');
  console.log('   - Subscription tier: max (all features)');
  console.log('   - Games created: 15 (mock data)');
  console.log('   - Reputation score: 850');
  console.log('   - Restart your dev server: npm run dev');
  console.log('   - Access protected routes directly:');
  console.log('     • http://localhost:3000/dashboard');
  console.log('     • http://localhost:3000/game-creator');
  console.log('     • http://localhost:3000/profile');
}

function disableDevMode() {
  const env = readEnvFile();
  env.DEV_MODE_ENABLED = 'false';
  env.NEXT_PUBLIC_DEV_MODE_ENABLED = 'false';
  // Keep NODE_ENV as development for local development
  
  writeEnvFile(env);
  
  console.log('❌ GameGen Dev Mode DISABLED');
  console.log('   - Normal authentication is now required');
  console.log('   - Restart your dev server: npm run dev');
  console.log('   - You will need to sign up/login normally');
  console.log('   - Protected routes will redirect to /auth');
}

// Main execution
const command = process.argv[2];

switch (command) {
  case 'on':
  case 'enable':
  case 'true':
    enableDevMode();
    break;
    
  case 'off':
  case 'disable':
  case 'false':
    disableDevMode();
    break;
    
  case 'status':
  case undefined:
    showStatus();
    break;
    
  default:
    console.log('Invalid command. Use "on", "off", or no argument to show status.');
    process.exit(1);
}